var _ = Describe("parseOutputSections", func() {
	var ctx context.Context

	BeforeEach(func() {
		ctx = context.Background()
	})

	It("parses multiple sections and their bullets in file order", func() {
		output := "<!--\n  AUTO-GENERATED\n-->\n\n# Title\n\n## Git\n\n" +
			"- **A.** alpha\n  continued line\n\n" +
			"- **B.** beta\n\n" +
			"## Ops\n\n" +
			"- **C.** gamma\n"

		sections, err := parseOutputSections(ctx, output)
		Expect(err).NotTo(HaveOccurred())
		Expect(sections).To(HaveLen(2))
		Expect(sections[0].Name).To(Equal("Git"))
		Expect(sections[0].Bullets).To(Equal([]string{
			"- **A.** alpha\n  continued line",
			"- **B.** beta",
		}))
		Expect(sections[1].Name).To(Equal("Ops"))
		Expect(sections[1].Bullets).To(Equal([]string{"- **C.** gamma"}))
	})

	It("ignores the auto-generated header, the title, and blank lines", func() {
		output := "<!--\n  AUTO-GENERATED by distill\n-->\n\n# Title\n\n## Git\n\n" +
			"- **A.** alpha\n"

		sections, err := parseOutputSections(ctx, output)
		Expect(err).NotTo(HaveOccurred())
		Expect(sections).To(HaveLen(1))
		Expect(sections[0].Bullets).To(Equal([]string{"- **A.** alpha"}))
	})

	It("treats markers inside a fenced code block as content", func() {
		output := "## Git\n\n" +
			"- **A.** use:\n" +
			"```\n" +
			"## not a section\n" +
			"- not a bullet\n" +
			"```\n"

		sections, err := parseOutputSections(ctx, output)
		Expect(err).NotTo(HaveOccurred())
		Expect(sections).To(HaveLen(1))
		Expect(sections[0].Bullets).To(Equal([]string{
			"- **A.** use:\n```\n## not a section\n- not a bullet\n```",
		}))
	})

	It("returns an error for a bullet before the first section heading", func() {
		_, err := parseOutputSections(ctx, "- **A.** orphan\n")
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring("bullet before first section heading"))
	})

	It("returns an error for a column-0 list item that is not a bold bullet", func() {
		_, err := parseOutputSections(ctx, "## Git\n\n- plain item\n")
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring("column-0 list item is not a bold bullet"))
	})

	It("returns an error for a duplicate section heading", func() {
		_, err := parseOutputSections(ctx, "## Git\n\n## Git\n")
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring(`duplicate section heading "Git"`))
	})

	It("returns no sections and no error for a header-only output", func() {
		output := "<!--\n  AUTO-GENERATED by distill\n-->\n\n# Title\n"
		sections, err := parseOutputSections(ctx, output)
		Expect(err).NotTo(HaveOccurred())
		Expect(sections).To(BeEmpty())
	})
})

var _ = Describe("attributeSections", func() {
	var ctx context.Context

	BeforeEach(func() {
		ctx = context.Background()
	})

	It("zips bullets onto enabled rules in emission order across sections", func() {
		allRules := []Rule{
			{ID: "a", Section: "Git"},
			{ID: "b", Section: "Git"},
			{ID: "c", Section: "Ops"},
		}
		enabled := []Rule{allRules[0], allRules[1], allRules[2]}
		sections := []outputSection{
			{Name: "Git", Bullets: []string{"- **A.** alpha", "- **B.** beta"}},
			{Name: "Ops", Bullets: []string{"- **C.** gamma"}},
		}

		bulletByID, err := attributeSections(ctx, allRules, enabled, sections)
		Expect(err).NotTo(HaveOccurred())
		Expect(bulletByID).To(Equal(map[string]string{
			"a": "- **A.** alpha",
			"b": "- **B.** beta",
			"c": "- **C.** gamma",
		}))
	})

	It("returns an error when an enabled section is missing from the output", func() {
		allRules := []Rule{{ID: "a", Section: "Git"}}
		enabled := []Rule{{ID: "a", Section: "Git"}}

		_, err := attributeSections(ctx, allRules, enabled, nil)
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring(`output is missing section "Git"`))
	})

	It("returns an error when the output has an unknown section heading", func() {
		allRules := []Rule{{ID: "a", Section: "Git"}}
		enabled := []Rule{{ID: "a", Section: "Git"}}
		sections := []outputSection{{Name: "Unknown"}}

		_, err := attributeSections(ctx, allRules, enabled, sections)
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring(`output section "Unknown" does not exist`))
	})

	It("returns an error when a section's bullet count disagrees", func() {
		allRules := []Rule{
			{ID: "a", Section: "Git"},
			{ID: "b", Section: "Git"},
		}
		enabled := []Rule{allRules[0], allRules[1]}
		sections := []outputSection{
			{Name: "Git", Bullets: []string{"- **A.** alpha"}},
		}

		_, err := attributeSections(ctx, allRules, enabled, sections)
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring(`section "Git" has 1 bullets but 2 enabled rules`))
	})

	It("accepts an all-disabled section heading with zero bullets", func() {
		allRules := []Rule{
			{ID: "a", Section: "Git"},
			{ID: "d", Section: "Ops", Disabled: true},
		}
		enabled := []Rule{allRules[0]}
		sections := []outputSection{
			{Name: "Git", Bullets: []string{"- **A.** alpha"}},
			{Name: "Ops"},
		}

		bulletByID, err := attributeSections(ctx, allRules, enabled, sections)
		Expect(err).NotTo(HaveOccurred())
		Expect(bulletByID).To(Equal(map[string]string{"a": "- **A.** alpha"}))
	})

	It("returns an error when an all-disabled section heading has bullets", func() {
		allRules := []Rule{
			{ID: "a", Section: "Git"},
			{ID: "d", Section: "Ops", Disabled: true},
		}
		enabled := []Rule{allRules[0]}
		sections := []outputSection{
			{Name: "Git", Bullets: []string{"- **A.** alpha"}},
			{Name: "Ops", Bullets: []string{"- **D.** orphan"}},
		}

		_, err := attributeSections(ctx, allRules, enabled, sections)
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring(`section "Ops" has bullets but no enabled rules`))
	})
})

var _ = Describe("rebuildFromOutput", func() {
	It("returns an error when the committed output cannot be read", func() {
		missing := filepath.Join(GinkgoT().TempDir(), "missing.md")

		_, err := rebuildFromOutput(context.Background(), missing, nil, nil)
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring("read committed output"))
	})
})
